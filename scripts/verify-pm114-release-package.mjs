import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
const root=process.cwd();
const manifest=JSON.parse(fs.readFileSync(path.join(root,"migration_release_manifest_p20_pm_appointment_reactivation_114.json"),"utf8"));
const migration=manifest.migrations?.[0];
const file=path.join(root,"migrations",migration?.filename||"");
const fail=(m)=>{console.error("BLOCKED: "+m);process.exit(1)};
if(manifest.production_application!=="not_authorized")fail("Production must remain unauthorized.");
if(manifest.owner_approval?.status!=="approved")fail("UAT approval evidence missing.");
if(manifest.uat_application?.status!=="applied"||manifest.uat_application?.branch_id!=="br-winter-butterfly-b3tnsao9"||manifest.uat_application?.ledger_id!==114)fail("Migration 114 UAT application evidence missing.");
if(manifest.migrations?.length!==1||migration?.migration_number!==114||migration?.status!=="prepared"||migration?.application_status!=="applied_uat"||migration?.source_sha_verified!==true)fail("Migration 114 release state invalid.");
if(!fs.existsSync(file))fail("Migration SQL missing.");
const actual=crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
if(actual!==migration.sha256)fail("Migration 114 SHA mismatch.");
const sql=fs.readFileSync(file,"utf8");
if((sql.match(/^BEGIN;$/gim)||[]).length!==1||(sql.match(/^COMMIT;$/gim)||[]).length!==1)fail("Transaction boundary missing.");
if(/^\s*(DROP\s+TABLE|DROP\s+SCHEMA|TRUNCATE)\b/im.test(sql))fail("Destructive DDL detected.");
console.log("PASS: Migration 114 release pin and UAT application evidence verified; Production remains unauthorized.");
