import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
const root=process.cwd();
const manifest=JSON.parse(fs.readFileSync(path.join(root,"migration_release_manifest_p20_field_capture_server_sync_115.json"),"utf8"));
const migration=manifest.migrations?.[0];
const file=path.join(root,"migrations",migration?.filename||"");
const fail=(m)=>{console.error("BLOCKED: "+m);process.exit(1)};
if(manifest.production_application!=="not_authorized")fail("Production must remain unauthorized.");
if(manifest.owner_approval?.status!=="pending")fail("This prepared package must not claim owner approval.");
if(manifest.uat_application?.status!=="not_applied"||manifest.uat_application?.ledger_id!==null)fail("Migration 115 must remain unapplied in UAT until explicit approval.");
if(manifest.migrations?.length!==1||migration?.migration_number!==115||migration?.status!=="prepared"||migration?.application_status!=="not_applied"||migration?.source_sha_verified!==true)fail("Migration 115 release state invalid.");
if(!fs.existsSync(file))fail("Migration SQL missing.");
const actual=crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
if(actual!==migration.sha256)fail("Migration 115 SHA mismatch.");
const sql=fs.readFileSync(file,"utf8");
if((sql.match(/^BEGIN;$/gim)||[]).length!==1||(sql.match(/^COMMIT;$/gim)||[]).length!==1)fail("Transaction boundary missing.");
if(/^\s*(DROP\s+TABLE|DROP\s+SCHEMA|TRUNCATE)\b/im.test(sql))fail("Destructive DDL detected.");
if(!sql.includes("FORCE ROW LEVEL SECURITY")||!sql.includes("project_field_capture_insert")||!sql.includes("actor_user_id=public.pke_current_user_id()"))fail("RLS security contract missing.");
console.log("PASS: Migration 115 SHA and prepared release gate verified; not applied to UAT or Production.");
